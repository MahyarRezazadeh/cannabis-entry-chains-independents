"""Write manifest.csv: every file in the package with its size, SHA-256, role, and redistribution status,
and output/logs/result_manifest.csv: every table and figure used in the paper with its producing script."""
import sys, pathlib, hashlib, csv
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "lib"))
from paths import ROOT

def role(rel):
    r = rel.replace("\\", "/")
    if r.startswith("data/raw/nm_crop"): return "raw input: NM Cannabis Control Division monthly sales (public records)", "redistributable (public records)"
    if r.startswith("data/raw/ref/uszips"): return "raw input: SimpleMaps US ZIP database, Basic", "redistributable (CC BY 4.0, attribution)"
    if r.startswith("data/raw/ref/cb_2023"): return "raw input: Census cartographic boundary file", "redistributable (public domain)"
    if r.startswith("data/raw/ref"): return "raw input: reference table", "redistributable"
    if r.startswith("data/raw/zbp"): return "raw input: ZIP Codes Business Patterns extract", "redistributable (public domain)"
    if r.startswith("data/intermediate/osrm"): return "constructed: OSRM travel-time matrix (OpenStreetMap)", "redistributable (ODbL attribution)"
    if r.startswith("data/intermediate/game_out"): return "saved outputs of the legacy static entry game", "redistributable (authors' output)"
    if r.startswith("data/intermediate"): return "constructed intermediate data", "redistributable"
    if r.startswith("data/analysis"): return "cached analysis objects (regenerated by run_all)", "regenerated"
    if r.startswith("code/legacy"): return "archived legacy code (not re-run; contains original absolute paths)", "code"
    if r.startswith("code"): return "code", "code"
    if r.startswith("output/tables/published"): return "archived published table (comparison target)", "output"
    if r.startswith("output/figures/published"): return "archived published figure", "output"
    if r.startswith("output"): return "generated output", "output"
    return "documentation", "documentation"

rows = []
for p in sorted(ROOT.rglob("*")):
    if p.is_file() and "__pycache__" not in p.parts and p.name != "manifest.csv":
        rel = str(p.relative_to(ROOT))
        h = hashlib.sha256(p.read_bytes()).hexdigest()
        r, lic = role(rel)
        rows.append([rel.replace("\\", "/"), p.stat().st_size, h, r, lic])
with open(ROOT / "manifest.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["path", "bytes", "sha256", "role", "redistribution"]); w.writerows(rows)

